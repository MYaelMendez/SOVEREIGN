BODIES = {
    "intro": INTRO_BODY,
    "list": LIST_BODY,
    "blocks": BLOCKS_BODY,
    "outro": OUTRO_BODY,
    "timeline": TIMELINE_BODY,
    "compare": COMPARE_BODY,
}


def geometry(s: dict) -> dict:
    w = s.get("width", 1920)
    h = s.get("height", 1080)
    return {
        "bg": "#050505", "gold": PALETTE["GOLD"], "goldhi": PALETTE["GOLDHI"],
        "cyan": PALETTE["CYAN"], "neon": PALETTE["NEON"], "txt": PALETTE["TXT"],
        "red": PALETTE["RED"], "mono": MONO,
        "f_line": 34, "line_gap": 62,
        "f_key": 30, "f_item": 26, "row_h": 0.62, "f_foot": 24,
        "f_head": 46, "card_h": 1.7, "f_block": 34, "f_block_sub": 22,
        "f_closer": 24,
        "f_tlhead": 44, "f_tlkey": 28, "f_tlitem": 22, "f_tlcloser": 22,
        "cmp_h": 4.2, "f_cmp": 32, "f_cmp_sub": 20, "f_cmp_body": 24,
        "f_cmp_small": 19, "f_vs": 46, "f_cmp_closer": 22,
    }


def emit(s: dict, out_dir: pathlib.Path | None = None) -> list[dict]:
    out_dir = out_dir or SCENES
    out_dir.mkdir(parents=True, exist_ok=True)
    g = geometry(s)
    written = []
    for e in s["episodes"]:
        acts = e["acts"]
        n = len(acts)
        classes = []
        for i, a in enumerate(acts):
            kind = a["kind"]
            if kind not in BODIES:
                continue
            body = BODIES[kind]
            vals = {k: v for k, v in a.items() if k != "kind"}
            vals.update(g)
            vals["i"] = i
            vals["kind"] = kind
            for k, v in vals.items():
                body = body.replace("{" + k + "}", str(v))
            classes.append(ACT_CLASS.replace("{i}", str(i)).replace("{kind}", kind).replace("{body}", body))
        py = HEADER.format(
            series=s["series"], bg=g["bg"], gold=g["gold"], goldhi=g["goldhi"],
            cyan=g["cyan"], neon=g["neon"], txt=g["txt"], red=g["red"], mono=g["mono"],
        ) + "\n".join(classes)
        fn = out_dir / f"{s['series']}-{e['id']}-{s.get('suffix','916')}.py"
        fn.write_text(py, encoding="utf-8")
        spec = {
            "title": f"{s['brand']} — {e['title']}",
            "text": e["subtitle"],
            "duration": s.get("duration", 18),
            "fps": s.get("fps", 30),
            "width": s.get("width", 1920),
            "height": s.get("height", 1080),
            "scene_py": fn.name,
            "render_path": "manim",
        }
        sp = SPECS / f"spec-{s['series']}-{e['id']}-{s.get('suffix','916')}.json"
        sp.write_text(json.dumps(spec, indent=2, ensure_ascii=False), encoding="utf-8")
        written.append({"episode": e["id"], "scene_py": str(fn), "spec": str(sp)})
    return written


def main(argv):
    ap = argparse.ArgumentParser(description="the same spec, rendered by Manim")
    sub = ap.add_subparsers(dest="cmd")
    for c in ("check", "emit"):
        p = sub.add_parser(c)
        p.add_argument("series")
    a = ap.parse_args(argv[1:])

    path = pathlib.Path(a.series)
    if not path.exists():
        print(f"  no such series: {path}"); return 1
    s = json.loads(path.read_text(encoding="utf-8"))

    if a.cmd == "check":
        for e in s["episodes"]:
            kinds = [x["kind"] for x in e["acts"]]
            print(f"    {e['id']:18s} {len(e['acts'])} acts  {kinds}")
        print("  ✓ valid")
        return 0

    written = emit(s)
    print(f"\n  emitted {len(written)} Manim scene(s):")
    for w in written:
        print(f"    {pathlib.Path(w['scene_py']).name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
