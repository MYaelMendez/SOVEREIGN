#!/usr/bin/env python3
"""
manim_builder.py — the same series spec, rendered by Manim CE.

THE INSIGHT
-----------
A series is data. The render PATH is a choice, not a rewrite. The same JSON
spec that produces an HTML+Canvas scene (fast, gold-on-void, 9:16 social) can
produce a Manim CE scene (educational cinema, mathematical, 1920x1080):

    series.json  →  manim_scene.py  →  manim -qh  →  gate  →  deploy

The act kinds are IDENTICAL. Only the emitter changes. That is the point:
two render engines, one content contract.

WHAT THIS EMITTER PRODUCES
--------------------------
One Python file with one Scene class per act, per the spec. Each class is
independently renderable (`manim -ql scene.py Act0_Intro`). Scenes are stitched
with ffmpeg after a per-scene gate.

COMMANDS
    python manim_builder.py emit   <series.json>   # write scene .py + render spec
    python manim_builder.py check  <series.json>   # validate + report
"""
