VIDEO_DIR = Path(r"C:\æ\threejs-curriculo")


def probe(path: Path) -> dict:
    """Real metadata from ffprobe. No invented numbers."""
    cmd = [FFPROBE, "-v", "error", "-select_streams", "v:0",
           "-show_entries", "stream=width,height,r_frame_rate,nb_frames",
           "-show_entries", "format=duration,size,bit_rate",
           "-of", "json", str(path)]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    d = json.loads(r.stdout)
    st = d["streams"][0]
    fmt = d["format"]
    num, den = st["r_frame_rate"].split("/")
    fps = round(int(num) / int(den))
    return {
        "width": st["width"], "height": st["height"], "fps": fps,
        "frames": int(st.get("nb_frames", 0)),
        "duration_s": round(float(fmt["duration"]), 1),
        "size_mb": round(int(fmt["size"]) / 1048576, 1),
        "bitrate_mbps": round(int(fmt["bit_rate"]) / 1e6, 1),
    }


def build() -> dict:
    entries = []
    for item in CATALOG:
        path = VIDEO_DIR / item["file"]
        if not path.exists():
            entries.append({**item, "status": "missing"})
            continue

        meta = probe(path)
        # Supervise the actual file — this is the verification receipt
        report = supervisar_video(str(path), muestrear=20)
        entries.append({
            **item,
            "status": "published",
            **meta,
            "vision": {
                "calidad": report["calidad"],
                "luminancia": report["luminancia_media"],
                "contraste": report["contraste_medio"],
                "movimiento": report["movimiento_medio"],
                "frames_negros": report["frames_negros"],
                "receipt": report["receipt"],
            },
        })

    published = [e for e in entries if e["status"] == "published"]
    total_mb = round(sum(e["size_mb"] for e in published), 1)
    total_frames = sum(e["frames"] for e in published)
    all_pass = all(e["vision"]["calidad"] == "PASS" for e in published)

    return {
        "factory": "æ://mp4-factory",
        "generated": "2026-10-04",
        "count": len(published),
        "total_mb": total_mb,
        "total_frames": total_frames,
        "all_pass": all_pass,
        "videos": entries,
    }


if __name__ == "__main__":
    manifest = build()
    out = sys.argv[1] if len(sys.argv) > 1 else "manifest.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)

    # Emit a JS twin so the web surface loads measured values, never typed ones.
    js_path = os.path.join(os.path.dirname(out), "manifest.js")
